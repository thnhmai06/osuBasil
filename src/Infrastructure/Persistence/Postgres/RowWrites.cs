using System.Linq.Expressions;
using Microsoft.EntityFrameworkCore;

namespace Basil.Infrastructure.Persistence.Postgres;

/// <summary>Stores a row whole, whether or not the database holds it already.</summary>
internal static class RowWrites
{
	extension(BasilDbContext context)
	{
		/// <summary>Stores a row: replaces the stored row with the same key, or adds the row when none is stored.</summary>
		/// <typeparam name="TRow">The type of the row.</typeparam>
		/// <param name="row">The row, with every value it should have.</param>
		/// <param name="key">The condition that finds the stored row of the same key.</param>
		/// <param name="cancellationToken">A token that cancels the write.</param>
		/// <remarks>The key of the row is given, never generated by the database.</remarks>
		public async Task UpsertAsync<TRow>(TRow row, Expression<Func<TRow, bool>> key,
			CancellationToken cancellationToken) where TRow : class
		{
			var stored = await context.Set<TRow>().AsTracking().FirstOrDefaultAsync(key, cancellationToken);
			if (stored is null)
				context.Add(row);
			else
				context.Entry(stored).CurrentValues.SetValues(row);
			await context.SaveChangesAsync(cancellationToken);
		}

		/// <summary>Replaces the stored row of the same key with a row, and does nothing when none is stored.</summary>
		/// <typeparam name="TRow">The type of the row.</typeparam>
		/// <param name="row">The row, with every value it should have.</param>
		/// <param name="key">The condition that finds the stored row of the same key.</param>
		/// <param name="cancellationToken">A token that cancels the write.</param>
		public async Task ReplaceAsync<TRow>(TRow row, Expression<Func<TRow, bool>> key,
			CancellationToken cancellationToken) where TRow : class
		{
			var stored = await context.Set<TRow>().AsTracking().FirstOrDefaultAsync(key, cancellationToken);
			if (stored is null)
				return;

			context.Entry(stored).CurrentValues.SetValues(row);
			await context.SaveChangesAsync(cancellationToken);
		}
	}
}