-- Basil baseline schema.
-- Conventions: snake_case names; ids from identity columns or sequences; times are timestamptz in UTC;
-- MD5 as lowercase hex text.

create extension if not exists pg_trgm;

create table users
(
	id          integer generated by default as identity primary key check (id >= 1),
	name        text        not null,
	country     integer     not null,
	permissions bigint      not null,
	deleted_at  timestamptz null
) with (fillfactor = 90);

-- A name is unique among accounts that are not deleted, after normalization (lower case, space equal to underscore), so a
-- deleted account frees its name.
create unique index users_name_live on users ((lower(replace(name, ' ', '_')))) where deleted_at is null;

-- Partial-name search; kept only if measured useful.
create index users_name_trgm on users using gin ((lower(replace(name, ' ', '_'))) gin_trgm_ops);

create table credentials
(
	user_id       integer primary key references users (id),
	password_hash text not null
);

create table logins
(
	id                    bigint generated always as identity primary key,
	user_id               integer     not null references users (id),
	ip                    inet        not null,
	timestamp             timestamptz not null,
	client_date           text        null,
	client_revision       integer     null,
	client_stream         integer     null,
	osu_path_hash         text        null,
	network_adapters      text        null,
	network_adapters_hash text        null,
	uninstall_hash        text        null,
	disk_signature_hash   text        null
);

create index logins_user_id_timestamp on logins (user_id, timestamp desc);

create table restrictions
(
	id          integer generated by default as identity primary key check (id >= 1),
	user_id     integer     not null references users (id),
	permissions bigint      not null,
	starts_at   timestamptz not null,
	ends_at     timestamptz null
);

create index restrictions_user_id on restrictions (user_id);

create table relationships
(
	actor_id   integer     not null references users (id),
	target_id  integer     not null references users (id),
	type       integer     not null,
	created_at timestamptz not null,
	primary key (actor_id, target_id)
);

create table channels
(
	name              text primary key,
	topic             text    not null,
	read_permissions  bigint  not null,
	write_permissions bigint  not null,
	auto_join         boolean not null,
	visible           boolean not null
);

